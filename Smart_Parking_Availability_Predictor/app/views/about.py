"""Page - About: what the project is, how it works, and its limits."""

import streamlit as st

from app import ui
from src import config


def render(ctx):
    ui.page_header("About this project", "Smart Parking Availability Predictor")
    meta = ctx.metadata
    split = meta.get("split", {})

    st.markdown(
        "A beginner-friendly machine learning project that predicts how full a parking lot "
        "will be from the **hour, weekday, weather and special events**.")

    st.subheader("How it works")
    first_step = ("1. **Simulated data** is generated by rules (daily patterns + weather + events + noise).\n"
                  if ctx.is_simulated else
                  "1. **Your parking data** (supplied with `python main.py --data`) is checked and loaded.\n")
    st.markdown(
        first_step +
        "2. The data is **cleaned** and **time features** are engineered.\n"
        "3. Several models are tuned and compared on time-ordered cross-validation; the best one is saved with Joblib.\n"
        "4. This dashboard **loads the saved data and model** - it never retrains and never invents numbers.\n"
        "5. **Recommendations** rank locations by the model's predicted free spaces, and **time slots** forecast "
        "the next hours.")

    st.subheader("Model facts")
    if meta:
        metrics = meta.get("test_metrics", {})
        ui.kpi_row([
            {"label": "Best model", "value": meta.get("best_model", "-")},
            {"label": "Test R²", "value": f"{metrics.get('test_r2', float('nan')):.3f}",
             "sub": "on unseen days"},
            {"label": "Test MAE", "value": f"{metrics.get('test_mae_spaces', float('nan')):.1f} spaces",
             "sub": "average miss"},
            {"label": "Records", "value": f"{len(ctx.df):,}",
             "sub": f"{config.NUM_DAYS} days, hourly"},
        ])
        if split:
            st.caption(f"Trained on data up to {split.get('train_end', '?')[:10]}; tested on "
                       f"{split.get('test_start', '?')[:10]} to {split.get('test_end', '?')[:10]} "
                       "(time-based split, so the test days are in the model's future).")
    else:
        st.info("Run `python main.py` to create the model metadata.")

    st.subheader("Status labels")
    ui.status_legend()

    st.subheader("Limitations")
    data_line = ("- The data is **simulated** (unless genuine data is supplied); scores describe the pipeline, "
                 "not real-world accuracy.\n" if ctx.is_simulated else
                 "- The data is the file you supplied; accuracy on other lots or periods is not guaranteed.\n")
    st.markdown(
        data_line +
        f"- Only {config.NUM_DAYS} days of history in the default dataset: no seasons, holidays or long-term trends.\n"
        "- The 'current' numbers on Home and Availability are a **snapshot from the dataset** "
        "(pick the moment in the sidebar); there is no live sensor feed.\n"
        "- Future weather is a user choice, not a forecast.\n"
        "- **Recommendations use predicted availability only**, not travel distance, unless you add "
        "`data/raw/lot_distances.csv`.\n"
        "- Predictions are **estimates**, not guaranteed real-time availability.")

    st.subheader("Project files")
    st.code("python main.py                         # create data, train, save model\n"
            "python main.py --train-only            # re-train on the saved dataset\n"
            "streamlit run app/streamlit_app.py     # this dashboard\n"
            "python -m unittest discover -s tests   # tests", language="bash")
